import { launch, newPage, sleep, speechWav } from "../lib.mjs";
import { mintSession } from "../session.mjs";
const BASE = process.env.BASE ?? "http://localhost:3001";
const results = [];
const check = (ok, label) => { results.push({ ok, label }); console.log(ok ? "  ✓" : "  ✗ FAIL", label); };
const visible = async (loc, timeout = 15000) => { try { await loc.first().waitFor({ state: "visible", timeout }); return true; } catch { return false; } };
const gone = async (loc, timeout = 10000) => { try { await loc.first().waitFor({ state: "detached", timeout }); return true; } catch { return false; } };
const until = async (fn, timeout = 20000) => { const end = Date.now() + timeout; while (Date.now() < end) { try { if (await fn()) return true; } catch {} await sleep(300); } return false; };

const browser = await launch({ args: ["--use-fake-ui-for-media-stream", "--use-fake-device-for-media-stream", `--use-file-for-fake-audio-capture=${speechWav()}`, "--auto-select-desktop-capture-source=Entire screen", "--auto-accept-this-tab-capture"] });
const mk = async (sub, name) => { const c = await newPage(browser, { width: 1280, height: 800 }); await c.context.addInitScript(() => { window.__gum = 0; const md = navigator.mediaDevices; if (md?.getUserMedia) { const original = md.getUserMedia.bind(md); md.getUserMedia = (...args) => { window.__gum++; return original(...args); }; } }); if (sub) await c.context.addCookies([await mintSession(sub, name)]); return c.page; };
const row = (page, name) => page.locator(`button[aria-label='${name}, open profile']`);

console.log("Setup: owner, a second Discord user and a guest");
const owner = await mk("discord-own-2", "Owner Two");
await owner.goto(BASE);
await owner.click("text=Create room");
await owner.waitForURL(/\/room\//);
const roomId = owner.url().split("/room/")[1];
await owner.getByRole("button", { name: "Join room" }).click();
const other = await mk("discord-two", "Other Two");
await other.goto(`${BASE}/room/${roomId}`);
await other.getByRole("button", { name: "Join room" }).click();
const guest = await mk(null, "");
await guest.goto(`${BASE}/login?callbackUrl=${encodeURIComponent(`/room/${roomId}`)}`);
await guest.fill("input[name=name]", "Viewer Guest");
await guest.click("text=Continue as guest");
await owner.getByRole("button", { name: "Let in" }).click({ timeout: 20000 });
await guest.getByRole("button", { name: "Join room" }).click({ timeout: 25000 });
for (const page of [owner, other, guest]) await page.getByRole("tab", { name: "People" }).click();
check(await until(async () => (await row(guest, "Owner Two").count()) > 0 && (await row(guest, "Other Two").count()) > 0), "everyone sees everyone in People");

console.log("Joining muted and deafened");
check(await visible(owner.getByRole("button", { name: "Unmute", exact: true })), "you join muted (the button offers Unmute)");
check(await visible(owner.getByRole("button", { name: "Undeafen", exact: true })), "you join deafened (the button offers Undeafen)");
check(await visible(row(guest, "Owner Two").locator("[title='Deafened']")), "others see the new joiner as deafened");
await sleep(1500);
check((await owner.evaluate(() => window.__gum)) === 0, "the microphone is not requested at join");
await owner.getByRole("button", { name: "Unmute", exact: true }).click();
check(await until(async () => (await owner.evaluate(() => window.__gum)) > 0), "the microphone is requested when you unmute");
check(await visible(owner.getByRole("button", { name: "Mute", exact: true })), "unmuting also undeafens you");
await other.getByRole("button", { name: "Unmute", exact: true }).click();
await visible(other.getByRole("button", { name: "Mute", exact: true }));

console.log("Voice panel layout");
check(await visible(owner.getByRole("button", { name: "Mute", exact: true })), "panel has a labelled Mute button");
check(await visible(owner.getByRole("button", { name: "Deafen", exact: true })), "panel has a labelled Deafen button");
check(await visible(owner.getByRole("button", { name: "Share your screen" })), "panel has Share for signed-in users");
check((await guest.getByRole("button", { name: /Share/ }).count()) === 0, "guests have no Share button");
await owner.screenshot({ path: "e2e2-panel.png" });

console.log("Speaking indicator");
const ringOn = (page, name) => row(page, name).locator("span.bg-live").count().then((n) => n > 0);
const speakingSeen = await until(async () => (await ringOn(guest, "Owner Two")) || (await ringOn(guest, "Other Two")), 25000);
check(speakingSeen, "the green speaking ring appears for someone talking (fake mic)");
check(await until(async () => (await owner.locator("span.bg-live").count()) > 0, 25000), "the voice panel ring shows when you talk");
await owner.getByRole("button", { name: "Mute", exact: true }).click();
check(await until(async () => !(await ringOn(guest, "Owner Two")), 8000), "the ring turns off as soon as someone mutes");

console.log("Voice status icons (everyone sees everyone)");
check(await visible(row(guest, "Owner Two").locator("[title='Muted']")), "self-muted shows a Muted icon to others");
await owner.getByRole("button", { name: "Unmute", exact: true }).click();
await owner.getByRole("button", { name: "Deafen", exact: true }).click();
check(await visible(row(guest, "Owner Two").locator("[title='Deafened']")), "self-deafened shows a Deafened icon to others");
await owner.getByRole("button", { name: "Undeafen", exact: true }).click();
check(await gone(row(guest, "Owner Two").locator("[title='Deafened']")), "undeafen clears it");

await row(owner, "Other Two").click({ button: "right" });
const menu = owner.getByRole("menu");
await menu.getByRole("switch", { name: "Mute for everyone" }).click();
check(await visible(row(guest, "Other Two").locator("[title='Muted by the room owner']")), "owner-muted shows an owner-muted icon to everyone");
check(await visible(other.getByText("Muted by the owner").first()), "the muted person's own panel says it was the owner");
check(await visible(row(guest, "Other Two").getByText("Muted by the owner")), "the People row says Muted by the owner");
await menu.getByRole("switch", { name: "Deafen for everyone" }).click();
check(await visible(row(guest, "Other Two").locator("[title='Deafened by the room owner']")), "owner-deafened shows an owner-deafened icon to everyone");
await menu.getByRole("switch", { name: "Deafen for everyone" }).click();
await menu.getByRole("switch", { name: "Mute for everyone" }).click();
await owner.keyboard.press("Escape");
check(await gone(row(guest, "Other Two").locator("[title='Muted by the room owner']")), "clearing the restriction clears the icon");

console.log("Volume: the bottom of the slider is silent and settings are remembered");
await owner.getByRole("button", { name: /Add a stream|Add$/ }).first().click();
await owner.fill("input[placeholder='Paste a YouTube or Twitch link']", "https://www.youtube.com/watch?v=jNQXAC9IVRw");
await owner.getByRole("button", { name: "Play for everyone" }).click();
await guest.getByRole("tab", { name: "Chat" }).click();
check(await visible(guest.locator("iframe[src*='youtube']"), 30000), "stream is playing for the guest");
const vol = other.locator("input[aria-label='Volume']").first();
await other.locator("iframe[src*='youtube']").first().waitFor({ timeout: 30000 });
await vol.fill("0");
check((await other.evaluate(() => JSON.parse(localStorage.getItem("nexus-player-volume") ?? "{}"))).volume === 0, "volume 0 is stored as 0");
await vol.fill("0.02");
check((await other.evaluate(() => JSON.parse(localStorage.getItem("nexus-player-volume") ?? "{}"))).volume === 0, "values at the very bottom snap to silent");
await vol.fill("0.6");
check((await other.evaluate(() => JSON.parse(localStorage.getItem("nexus-player-volume") ?? "{}"))).volume === 0.6, "normal values are kept");
await other.reload();
await other.getByRole("button", { name: "Join room" }).click();
check(await until(async () => Number(await other.locator("input[aria-label='Volume']").first().inputValue()) === 0.6), "the volume survives a reload");

console.log("Subtitles");
const ccButton = other.getByRole("button", { name: "Subtitles", exact: true });
check(await visible(ccButton, 40000), "the Subtitles button appears when the video has caption tracks");
await ccButton.click();
const items = await other.getByRole("menuitemradio").allTextContents();
check(items[0] === "Off" && items.length >= 2, `the menu lists Off plus languages (${items.slice(0, 4).join(" | ")})`);
await other.screenshot({ path: "e2e2-captions-menu.png" });
await other.getByRole("menuitemradio").nth(1).click();
check(await until(async () => (await ccButton.getAttribute("aria-pressed")) === "true"), "choosing a language turns subtitles on");
check((await other.evaluate(() => JSON.parse(localStorage.getItem("nexus-captions") ?? "{}"))).on === true, "the choice is remembered");
await sleep(2500);
await other.screenshot({ path: "e2e2-captions-on.png" });
await ccButton.click();
await other.getByRole("button", { name: "Large", exact: true }).click();
check((await other.evaluate(() => JSON.parse(localStorage.getItem("nexus-captions") ?? "{}"))).size === 1, "text size can be changed and is remembered");
await other.keyboard.press("Escape");
await ccButton.click();
await other.getByRole("menuitemradio", { name: "Off", exact: true }).click();
check(await until(async () => (await ccButton.getAttribute("aria-pressed")) === "false"), "Off turns subtitles off");
check((await other.evaluate(() => JSON.parse(localStorage.getItem("nexus-captions") ?? "{}"))).on === false, "off is remembered");
await sleep(2500);
await other.screenshot({ path: "e2e2-captions-off.png" });

console.log("Multiple screen shares");
await owner.getByRole("button", { name: "Share your screen" }).click();
check(await visible(other.getByText("started sharing their screen"), 20000), "viewers get a 'started sharing' notice");
await other.getByRole("button", { name: "Share your screen" }).click();
check(await until(async () => (await guest.getByRole("button", { name: /^Watch .*'s screen$/ }).count()) >= 2, 25000) || (await guest.locator("section[aria-label='Streams'] li").count()) >= 3, "two people can share at once and the library lists both");
await guest.getByRole("tab", { name: "People" }).click();
check(await visible(row(guest, "Owner Two").getByText("Sharing their screen")), "People shows who is sharing");
await owner.screenshot({ path: "e2e2-multishare-owner.png" });
const otherCard = owner.locator("section[aria-label='Streams'] li", { hasText: "Other Two's screen" });
await otherCard.getByRole("button", { name: "More actions", exact: true }).click();
await owner.getByRole("menuitem", { name: "Show to everyone" }).click();
check(await until(async () => (await guest.locator("h1").first().innerText()).includes("Other Two's screen")), "putting a screen on air moves everyone to it");
await guest.screenshot({ path: "e2e2-multishare-guest.png" });
await otherCard.getByRole("button", { name: "More actions", exact: true }).click();
await owner.getByRole("menuitem", { name: "Stop their screen share" }).click();
check(await until(async () => (await other.getByRole("button", { name: "Share your screen" }).count()) > 0, 15000), "the owner can stop someone else's screen share");
check(await gone(guest.locator("section[aria-label='Streams'] li", { hasText: "Other Two's screen" }), 15000), "the stopped share disappears for viewers");

console.log("Sharing policy");
await owner.getByRole("button", { name: "Room settings" }).click();
await owner.getByRole("dialog").getByRole("tab", { name: "Controllers only" }).click();
await owner.keyboard.press("Escape");
check(await until(async () => await other.getByRole("button", { name: /Only controllers can share/ }).isDisabled().catch(() => false), 15000), "with 'Controllers only', other people's Share is disabled");
check(await visible(other.getByText("Only controllers can share their screen in this room.")), "they are told why");
check(await owner.getByRole("button", { name: /Stop sharing|Share your screen/ }).first().isEnabled(), "the owner can still share");

await browser.close();
const failed = results.filter((r) => !r.ok);
console.log(`\n${results.length - failed.length}/${results.length} checks passed`);
process.exit(failed.length ? 1 : 0);
