import { launch, newPage, sleep } from "../lib.mjs";
import { mintSession } from "../session.mjs";
const BASE = process.env.BASE ?? "http://localhost:3001";
const results = [];
const check = (ok, label) => { results.push({ ok, label }); console.log(ok ? "  ✓" : "  ✗ FAIL", label); };
const visible = async (loc, timeout = 15000) => { try { await loc.first().waitFor({ state: "visible", timeout }); return true; } catch { return false; } };
const gone = async (loc, timeout = 8000) => { try { await loc.first().waitFor({ state: "detached", timeout }); return true; } catch { return false; } };

const browser = await launch();
const owner = await newPage(browser, { width: 1280, height: 800 });
await owner.context.addCookies([await mintSession("discord-owner-1", "Owner One")]);
const op = owner.page;

console.log("Owner creates a named room");
await op.goto(BASE);
await op.fill("input[placeholder='Room name (optional)']", "Worlds night");
await op.click("text=Create room");
await op.waitForURL(/\/room\//);
const roomId = op.url().split("/room/")[1];
await op.getByRole("button", { name: "Join room" }).click();
check(await visible(op.getByText("Worlds night", { exact: true })), "room name shows in the header");
check((await op.title()) === "Worlds night · Nexus Lounge", "browser tab title uses the room name");

console.log("Guest knocks, owner admits");
const guest = await newPage(browser, { width: 1280, height: 800 });
const gp = guest.page;
await gp.goto(`${BASE}/login?callbackUrl=${encodeURIComponent(`/room/${roomId}`)}`);
await gp.fill("input[name=name]", "Guest One");
await gp.click("text=Continue as guest");
check(await visible(gp.getByText("Waiting to be let in")), "guest sees the waiting screen");
check(await visible(op.getByText("Guest, waiting to join")), "owner sees a join request card");
await op.screenshot({ path: "e2e-join-request.png" });
await op.getByRole("button", { name: "Let in" }).click();
check(await visible(gp.getByRole("button", { name: "Join room" }), 20000), "guest is let in");
await gp.getByRole("button", { name: "Join room" }).click();
check(await visible(gp.getByText("Worlds night", { exact: true })), "guest sees the room name");

console.log("People: right-click menu and profile");
await op.getByRole("tab", { name: "People" }).click();
const row = op.locator("button[aria-label='Guest One, open profile']");
check(await visible(row, 20000), "guest appears in the owner's People list");
await row.click({ button: "right" });
const menu = op.getByRole("menu");
check(await visible(menu), "right-click opens the quick menu");
check(await menu.getByLabel("Volume").count() > 0, "quick menu has a volume slider");
check(await menu.getByRole("switch", { name: "Mute for me" }).count() > 0, "quick menu has Mute for me");
check(await menu.getByRole("switch", { name: "Mute for everyone" }).count() > 0, "owner sees Mute for everyone");
check(await menu.getByRole("switch", { name: "Deafen for everyone" }).count() > 0, "owner sees Deafen for everyone");
await menu.locator("input[type=range]").fill("40");
check(await menu.getByText("40%").count() > 0, "volume slider changes the percentage");
await op.screenshot({ path: "e2e-quick-menu.png" });
await menu.getByRole("switch", { name: "Mute for me" }).click();
check(await menu.getByText("Muted", { exact: true }).count() > 0, "Mute for me shows muted");
await menu.getByRole("switch", { name: "Mute for me" }).click();
await menu.getByRole("button", { name: /View profile/ }).click();
const dialog = op.getByRole("dialog");
check(await visible(dialog), "View profile opens the profile card");
check((await dialog.innerText()).includes("Connection"), "profile card shows connection quality");
await op.screenshot({ path: "e2e-profile.png" });
await op.keyboard.press("Escape");

console.log("Streams, reactions");
await op.getByRole("button", { name: /Add a stream|Add$/ }).first().click();
await op.fill("input[placeholder='Paste a YouTube or Twitch link']", "https://www.youtube.com/watch?v=jNQXAC9IVRw");
await op.getByRole("button", { name: "Play for everyone" }).click();
check(await visible(gp.locator("iframe[src*='youtube']"), 30000), "guest gets the featured YouTube player");
check(await visible(op.getByText("Me at the zoo").first(), 20000), "title is fetched and shown");
await gp.getByRole("button", { name: "React 🔥" }).click();
await sleep(800);
check((await op.locator(".animate-reaction").count()) > 0, "owner sees the floating reaction");
await op.screenshot({ path: "e2e-reaction.png" });

console.log("Queue");
await op.getByRole("button", { name: /Add$/ }).first().click();
await op.fill("input[placeholder='Paste a YouTube or Twitch link']", "https://youtu.be/dQw4w9WgXcQ");
await op.getByRole("button", { name: "Add to library" }).click();
check(await visible(op.getByText("Up next", { exact: true }).first(), 15000), "the item after the featured one is marked Up next");
const cards = op.locator("section[aria-label='Streams'] li");
const order = async () => (await cards.allInnerTexts()).map((t) => t.split("\n")[0]);
const before = await order();
const second = cards.nth(1);
await second.getByRole("button", { name: "More actions", exact: true }).click();
await op.getByRole("menuitem", { name: "Move up" }).click();
await sleep(700);
const after = await order();
check(before[0] !== after[0] && before[0] === after[1], `Move up reorders the list (${before.map((t) => t.slice(0, 12))} -> ${after.map((t) => t.slice(0, 12))})`);
await op.screenshot({ path: "e2e-queue.png" });

console.log("Room settings");
await op.getByRole("button", { name: "Room settings" }).click();
const settings = op.getByRole("dialog");
check(await visible(settings), "owner can open room settings");
await op.screenshot({ path: "e2e-settings.png" });
await settings.getByRole("switch", { name: "Reactions" }).click();
check(await gone(gp.getByRole("group", { name: "Send a reaction" })), "turning reactions off removes the bar for guests");
await settings.getByRole("switch", { name: "Reactions" }).click();
check(await visible(gp.getByRole("group", { name: "Send a reaction" })), "turning reactions back on restores it");
await settings.getByRole("tab", { name: "Not allowed" }).click();
const guest2 = await newPage(browser, { width: 1280, height: 800 });
await guest2.page.goto(`${BASE}/login?callbackUrl=${encodeURIComponent(`/room/${roomId}`)}`);
await guest2.page.fill("input[name=name]", "Guest Two");
await guest2.page.click("text=Continue as guest");
check(await visible(guest2.page.getByText("doesn't allow guests")), "guests are turned away when guests are not allowed");
await settings.getByRole("tab", { name: "Let in" }).click();
await guest2.page.reload();
check(await visible(guest2.page.getByRole("button", { name: "Join room" }), 20000), "with Let in, a new guest walks straight in");
await settings.getByRole("tab", { name: "Ask me" }).click();
await settings.getByRole("switch", { name: "Lock room" }).click();
const newcomer = await newPage(browser, { width: 1280, height: 800 });
await newcomer.context.addCookies([await mintSession("discord-newcomer", "Newcomer")]);
await newcomer.page.goto(`${BASE}/room/${roomId}`);
check(await visible(newcomer.page.getByText("This room is locked by the owner")), "a locked room turns new people away");
await settings.getByRole("switch", { name: "Lock room" }).click();
await op.keyboard.press("Escape");

console.log("Remove from room");
await row.click({ button: "right" });
await op.getByRole("menu").getByRole("button", { name: /Remove from room/ }).click();
await op.getByRole("menu").getByRole("button", { name: "Remove", exact: true }).click();
check(await visible(gp.getByText("You were removed")), "the removed guest sees the removal screen");
check(await gone(op.locator("button[aria-label='Guest One, open profile']")), "they disappear from the owner's list");

await browser.close();
const failed = results.filter((r) => !r.ok);
console.log(`\n${results.length - failed.length}/${results.length} checks passed`);
process.exit(failed.length ? 1 : 0);
